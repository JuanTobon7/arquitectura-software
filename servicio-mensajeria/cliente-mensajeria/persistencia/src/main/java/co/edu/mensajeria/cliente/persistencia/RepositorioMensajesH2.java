package co.edu.mensajeria.cliente.persistencia;

import co.edu.mensajeria.cliente.dto.MensajeChat;
import co.edu.mensajeria.cliente.dto.TipoMensaje;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

/**
 * Historial en una base H2 embebida: un archivo en el equipo, sin instalar nada.
 *
 * <p>La clave es (propietario, id): si dos usuarios usan el mismo cliente en el mismo equipo,
 * cada uno tiene su copia del mensaje que se enviaron. Guardar usa {@code MERGE}, así que
 * recibir de nuevo un mensaje ya guardado no lo duplica.</p>
 *
 * <p>Varios clientes en el mismo equipo comparten la base con {@code AUTO_SERVER=TRUE}: el
 * primero la abre y los demás se conectan a él. Si ese primero se cierra, otro toma la base;
 * en ese relevo una operación puede fallar, por eso cada una se reintenta unas pocas veces.</p>
 */
public class RepositorioMensajesH2 implements IRepositorioMensajesLocal {

    private static final String CREAR_TABLA = """
            CREATE TABLE IF NOT EXISTS mensajes_chat (
                propietario  VARCHAR(64)   NOT NULL,
                id           VARCHAR(64)   NOT NULL,
                contacto     VARCHAR(64)   NOT NULL,
                origen       VARCHAR(64)   NOT NULL,
                destino      VARCHAR(64)   NOT NULL,
                tipo         VARCHAR(10)   NOT NULL,
                fecha        TIMESTAMP(3)  NOT NULL,
                contenido    CLOB,
                ruta_archivo VARCHAR(1024),
                orden        BIGINT GENERATED BY DEFAULT AS IDENTITY,
                PRIMARY KEY (propietario, id)
            )""";
    private static final String CREAR_INDICE =
            "CREATE INDEX IF NOT EXISTS idx_conversacion ON mensajes_chat (propietario, contacto, fecha)";
    private static final String GUARDAR = """
            MERGE INTO mensajes_chat (propietario, id, contacto, origen, destino, tipo, fecha, contenido, ruta_archivo)
            KEY (propietario, id) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""";
    private static final String CONVERSACION = """
            SELECT id, propietario, contacto, origen, destino, tipo, fecha, contenido, ruta_archivo
            FROM mensajes_chat WHERE propietario = ? AND contacto = ? ORDER BY fecha, orden""";

    static final int INTENTOS = 3;
    private static final long PAUSA_MS = 200;

    private final String url;
    private final String usuario;
    private final String contrasena;

    /** Crea la tabla si no existe. */
    public RepositorioMensajesH2(String url, String usuario, String contrasena) {
        this.url = url;
        this.usuario = usuario;
        this.contrasena = contrasena;
        ejecutar("No se pudo abrir el historial local en " + url, c -> {
            try (Statement st = c.createStatement()) {
                st.execute(CREAR_TABLA);
                st.execute(CREAR_INDICE);
            }
            return null;
        });
    }

    @Override
    public void guardar(MensajeChat m) {
        ejecutar("No se pudo guardar el mensaje " + m.id(), c -> {
            try (PreparedStatement ps = c.prepareStatement(GUARDAR)) {
                llenar(ps, m);
                return ps.executeUpdate();
            }
        });
    }

    @Override
    public List<MensajeChat> conversacion(String propietario, String contacto) {
        return ejecutar("No se pudo leer la conversación con " + contacto, c -> {
            try (PreparedStatement ps = c.prepareStatement(CONVERSACION)) {
                ps.setString(1, propietario);
                ps.setString(2, contacto);
                List<MensajeChat> mensajes = new ArrayList<>();
                try (ResultSet rs = ps.executeQuery()) {
                    while (rs.next()) {
                        mensajes.add(leer(rs));
                    }
                }
                return mensajes;
            }
        });
    }

    /** Abre una conexión, ejecuta la operación y la cierra; si falla, reintenta con una pausa. */
    private <T> T ejecutar(String error, Operacion<T> operacion) {
        SQLException ultima = null;
        for (int intento = 1; intento <= INTENTOS; intento++) {
            try (Connection c = conexion()) {
                return operacion.con(c);
            } catch (SQLException e) {
                ultima = e;
                pausa(intento);
            }
        }
        throw new ErrorPersistencia(error + ": " + ultima.getMessage(), ultima);
    }

    private Connection conexion() throws SQLException {
        return DriverManager.getConnection(url, usuario, contrasena);
    }

    private static void llenar(PreparedStatement ps, MensajeChat m) throws SQLException {
        ps.setString(1, m.propietario());
        ps.setString(2, m.id());
        ps.setString(3, m.contacto());
        ps.setString(4, m.origen());
        ps.setString(5, m.destino());
        ps.setString(6, m.tipo().name());
        ps.setObject(7, m.fecha());
        ps.setString(8, m.contenido());
        ps.setString(9, m.rutaArchivo());
    }

    private static MensajeChat leer(ResultSet rs) throws SQLException {
        return new MensajeChat(rs.getString("id"), rs.getString("propietario"), rs.getString("contacto"),
                rs.getString("origen"), rs.getString("destino"), TipoMensaje.valueOf(rs.getString("tipo")),
                rs.getObject("fecha", LocalDateTime.class), rs.getString("contenido"), rs.getString("ruta_archivo"));
    }

    private static void pausa(int intento) {
        if (intento == INTENTOS) {
            return;
        }
        try {
            Thread.sleep(PAUSA_MS * intento);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }
    }

    /** Una operación sobre una conexión abierta. */
    @FunctionalInterface
    private interface Operacion<T> {
        T con(Connection c) throws SQLException;
    }
}
